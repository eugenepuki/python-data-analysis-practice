grades = [18, 25, 30, 14, 27, 21]

def average_grade(grades):

    total = sum(grades)

    number_of_grades = len(grades)

    average = total / number_of_grades

    return average

def lowest_grade(grades):

    return min(grades)

def highest_grade(grades):

    return max(grades)

def count_passing_grades(grades):

    count = 0

    for grade in grades:

        if grade >= 18:

            count += 1

    return count

def filter_high_grades(grades):

    high_grades = []

    for grade in grades:

        if grade >= 25:

            high_grades.append(grade)

    return high_grades

# Display the results

print("Average grade:", average_grade(grades))

